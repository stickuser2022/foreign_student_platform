export const provinceToRu = (p: string) => provinceRu[p] ?? p;
export const cityToRu = (c: string) => cityRu[c] ?? c;

// "Пекин · Пекин" 这种省市同名只显示一次
export function geoToRu(province: string, city: string): string {
  const p = provinceToRu(province);
  const c = cityToRu(city);
  return p === c ? c : `${p} · ${c}`;
}
